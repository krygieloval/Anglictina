export function resolveEmoji(englishWord: string, fallback: string = '🖼️'): string {
  const key = englishWord.trim().toLowerCase();
  if (WORD_EMOJIS[key]) return WORD_EMOJIS[key];
  for (const [token, emoji] of Object.entries(WORD_EMOJIS)) {
    const escaped = token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    if (new RegExp(`\\b${escaped}\\b`, 'i').test(key)) {
      return emoji;
    }
  }
  return fallback || '🖼️';
}
